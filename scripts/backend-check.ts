const si = await again.auth.signInWithPassword({ email: winner.email, password: winner.password });
const persisted = await again.rpc("get_my_appointments");
const persistedDebt = await again.from("debts").select("id");
check("after sign-out and sign-in, bookings and debts are still there", !si.error && persisted.data?.some((a) => a.id === appt.id) === true && persistedDebt.data?.length === 1, msg(si));

console.log(failures === 0 ? "\nALL PASSED" : `\n${failures} FAILED`);
