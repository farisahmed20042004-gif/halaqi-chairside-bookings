// Phase 1 acceptance checks against the real backend.
// Run: bun scripts/backend-check.ts   (creates throwaway accounts named halaqi.test.*)
import { createClient, type SupabaseClient } from "@supabase/supabase-js";

import type { Database } from "../src/integrations/supabase/types";

const url = process.env.VITE_SUPABASE_URL!;
const key = process.env.VITE_SUPABASE_PUBLISHABLE_KEY!;
const stamp = Date.now();
let failures = 0;
const check = (name: string, ok: boolean, extra?: unknown) => {
  if (!ok) failures++;
  console.log(`${ok ? "PASS" : "FAIL"}  ${name}${!ok && extra !== undefined ? "  " + JSON.stringify(extra) : ""}`);
};
const msg = (r: { error: { message: string } | null }) => r.error?.message ?? "";
type C = SupabaseClient<Database>;
const newClient = () => createClient<Database>(url, key, { auth: { persistSession: false, autoRefreshToken: false } });

async function user(tag: string, fullName: string, type: "barber" | "customer") {
  const c = newClient();
  const email = `halaqi.test.${tag}.${stamp}@example.com`;
  const password = `Test-${stamp}-Xy9!q`;
  const { data, error } = await c.auth.signUp({ email, password, options: { data: { full_name: fullName, account_type: type } } });
  if (error || !data.session) throw new Error(`signup ${tag}: ${error?.message ?? "no session"}`);
  return { c: c as C, id: data.user!.id, email, password };
}

// ---------- Accounts & roles ----------
const barberA = await user("barbera", "حلاق أ", "barber");
const barberB = await user("barberb", "حلاق ب", "barber");
const cust1 = await user("cust1", "زبون ١", "customer");
const cust2 = await user("cust2", "زبون ٢", "customer");
const cust3 = await user("cust3", "زبون ٣", "customer");
check("sign-up gives an immediate session", true);

const roleA = await barberA.c.from("user_roles").select("role").single();
const role1 = await cust1.c.from("user_roles").select("role").single();
check("barber account gets the barber role", roleA.data?.role === "barber", roleA.error?.message);
check("customer account gets the customer role", role1.data?.role === "customer", role1.error?.message);
const selfPromote = await cust1.c.from("user_roles").update({ role: "barber" }).eq("user_id", cust1.id).select();
check("customer cannot change own role", (selfPromote.data ?? []).length === 0);
const custShop = await cust1.c.from("barbers").insert({ owner_id: cust1.id, shop_name: "صالون مزيف", barber_name: "زبون" });
check("customer account cannot create a shop", !!custShop.error);

// ---------- Shops & services ----------
const { data: shopA, error: eA } = await barberA.c
  .from("barbers")
  .insert({ owner_id: barberA.id, shop_name: "صالون أ", barber_name: "حلاق أ", address: "بغداد", code: "HACK-1" })
  .select()
  .single();
check("barber A creates shop with address", !!shopA && shopA.address === "بغداد", eA?.message);
check("shop code generated by server", /^HLQ-[A-Z2-9]{6}$/.test(shopA?.code ?? ""), shopA?.code);
const { data: shopB } = await barberB.c.from("barbers").insert({ owner_id: barberB.id, shop_name: "صالون ب", barber_name: "حلاق ب" }).select().single();
check("shop codes are unique", !!shopB && shopB.code !== shopA!.code);
check("barber B cannot read A's shop row", ((await barberB.c.from("barbers").select("*").eq("id", shopA!.id)).data ?? []).length === 0);

const svc = await barberA.c
  .from("services")
  .insert([
    { barber_id: shopA!.id, name: "قص شعر", price: 10000, duration_minutes: 30, is_active: true },
    { barber_id: shopA!.id, name: "قص + ذقن", price: 15000, duration_minutes: 60, is_active: true },
    { barber_id: shopA!.id, name: "خدمة موقوفة", price: 5000, duration_minutes: 30, is_active: false },
  ])
  .select();
check("barber adds services with price and duration", svc.data?.length === 3, msg(svc));
const cut = svc.data!.find((s) => s.name === "قص شعر")!;
const combo = svc.data!.find((s) => s.name === "قص + ذقن")!;
const off = svc.data!.find((s) => s.name === "خدمة موقوفة")!;
const bSvc = await barberB.c.from("services").insert({ barber_id: shopA!.id, name: "حيلة", price: 1, duration_minutes: 30 });
check("barber B cannot add services to A's shop", !!bSvc.error);
check("customer cannot add services", !!(await cust1.c.from("services").insert({ barber_id: shopA!.id, name: "حيلة", price: 1, duration_minutes: 30 })).error);

const found = await cust1.c.rpc("find_barber_by_code", { p_code: " " + shopA!.code.toLowerCase() + " " });
check("customer finds shop by code", found.data?.[0]?.id === shopA!.id, msg(found));
check("lookup does not expose owner id", !("owner_id" in (found.data?.[0] ?? {})));
const menu = await cust1.c.rpc("get_shop_services", { p_barber_id: shopA!.id });
check("customer sees only active services with prices", menu.data?.length === 2 && menu.data.every((s) => s.price > 0), msg(menu));

// ---------- Booking ----------
const tomorrow = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Baghdad" }).format(new Date(Date.now() + 86400000));
const slots = await cust1.c.rpc("get_available_slots", { p_barber_id: shopA!.id, p_day: tomorrow, p_service_id: combo.id });
check("60-min service: 21 start times between 10:00 and 21:00", slots.data?.length === 21, msg(slots) || slots.data?.length);
const T = slots.data![4]!.starts_at; // 12:00
const plus = (iso: string, m: number) => new Date(new Date(iso).getTime() + m * 60000).toISOString();
const book = (u: { c: C }, serviceId: string, at: string) =>
  u.c.rpc("book_appointment", { p_barber_id: shopA!.id, p_service_id: serviceId, p_starts_at: at });

const [r1, r2] = await Promise.all([book(cust1, combo.id, T), book(cust2, combo.id, T)]);
const wins = [r1, r2].filter((r) => !r.error);
check("simultaneous booking of same slot: exactly one succeeds", wins.length === 1, [msg(r1), msg(r2)]);
check("the other gets SLOT_TAKEN", [msg(r1), msg(r2)].some((m) => m.includes("SLOT_TAKEN")));
const appt = wins[0]!.data!;
const winner = r1.error ? cust2 : cust1;
const loser = r1.error ? cust1 : cust2;
check("booking is confirmed and stores service, price and duration", appt.status === "confirmed" && appt.service_id === combo.id && appt.price === 15000 && appt.duration_minutes === 60);

const overlap = await book(loser, cut.id, plus(T, 30));
check("overlapping booking (inside a 60-min appointment) rejected", msg(overlap).includes("SLOT_TAKEN"), msg(overlap));
const [o1, o2] = await Promise.all([book(loser, combo.id, plus(T, 120)), book(cust3, cut.id, plus(T, 150))]);
check("simultaneous overlapping requests: only one succeeds", [o1, o2].filter((r) => !r.error).length === 1, [msg(o1), msg(o2)]);
const after = await cust1.c.rpc("get_available_slots", { p_barber_id: shopA!.id, p_day: tomorrow, p_service_id: cut.id });
const avail = (iso: string) => after.data?.find((s) => new Date(s.starts_at).getTime() === new Date(iso).getTime())?.available;
check("booked time and its covered half-hour show as taken", avail(T) === false && avail(plus(T, 30)) === false && avail(plus(T, 60)) === true);

check("inactive service cannot be booked", msg(await book(cust1, off.id, plus(T, 300))).includes("SERVICE_UNAVAILABLE"));
check("off-schedule time rejected", msg(await book(cust1, cut.id, plus(T, 7))).includes("OUTSIDE_HOURS"));
check("past time rejected", msg(await book(cust1, cut.id, new Date(Date.now() - 3600e3).toISOString())).includes("SLOT_IN_PAST"));
const bAsCustomer = await barberB.c.rpc("book_appointment", { p_barber_id: shopA!.id, p_service_id: cut.id, p_starts_at: plus(T, 360) });
check("a barber account cannot book at another shop as a customer", msg(bAsCustomer).includes("NOT_A_CUSTOMER"), msg(bAsCustomer));
const direct = await cust1.c.from("appointments").insert({ barber_id: shopA!.id, customer_name: "x y", service: "قص", starts_at: plus(T, 400) } as never);
check("direct insert bypassing the rules is blocked", !!direct.error);

await barberA.c.from("services").update({ price: 99000 }).eq("id", combo.id);
const kept = await barberA.c.from("appointments").select("price").eq("id", appt.id).single();
check("later price change does not alter the booked price", kept.data?.price === 15000, kept.data);

// ---------- Privacy ----------
check("other customer cannot see the booking", ((await loser.c.from("appointments").select("*").eq("id", appt.id)).data ?? []).length === 0);
const mine = await winner.c.rpc("get_my_appointments");
check("booking customer sees own booking", mine.data?.some((a) => a.id === appt.id) === true, msg(mine));
check("barber A sees the booking", ((await barberA.c.from("appointments").select("id").eq("id", appt.id)).data ?? []).length === 1);
check("barber B cannot see A's bookings", ((await barberB.c.from("appointments").select("*")).data ?? []).length === 0);
check("customer cannot change status directly", ((await winner.c.from("appointments").update({ status: "completed" }).eq("id", appt.id).select()).data ?? []).length === 0);
check("barber B cannot cancel A's booking", ((await barberB.c.from("appointments").update({ status: "cancelled" }).eq("id", appt.id).select()).data ?? []).length === 0);
const scA = await barberA.c.from("shop_customers").select("customer_id");
check("barber A sees customers who booked", scA.data?.some((r) => r.customer_id === winner.id) === true);
check("barber B sees none of A's customers", ((await barberB.c.from("shop_customers").select("*")).data ?? []).length === 0);

// ---------- Rescheduling ----------
const resc = await winner.c.rpc("reschedule_appointment", { p_id: appt.id, p_new_starts_at: plus(T, 240) });
check("customer reschedules own booking to a free time", !resc.error && resc.data?.starts_at && new Date(resc.data.starts_at).getTime() === new Date(plus(T, 240)).getTime(), msg(resc));
const freedOld = await cust1.c.rpc("get_available_slots", { p_barber_id: shopA!.id, p_day: tomorrow, p_service_id: cut.id });
check("old time is free again after rescheduling", freedOld.data?.find((s) => s.starts_at === T)?.available === true);
const takenTarget = !o1.error ? plus(T, 120) : plus(T, 150);
const rescTaken = await winner.c.rpc("reschedule_appointment", { p_id: appt.id, p_new_starts_at: takenTarget });
check("rescheduling into a taken time is rejected", msg(rescTaken).includes("SLOT_TAKEN"), msg(rescTaken));
const rescOther = await loser.c.rpc("reschedule_appointment", { p_id: appt.id, p_new_starts_at: plus(T, 420) });
check("another customer cannot reschedule my booking", msg(rescOther).includes("CANNOT_RESCHEDULE"), msg(rescOther));
const [x1, x2] = await Promise.all([
  winner.c.rpc("reschedule_appointment", { p_id: appt.id, p_new_starts_at: plus(T, 480) }),
  book(cust3, cut.id, plus(T, 480)),
]);
check("simultaneous reschedule and booking of same time: only one succeeds", [x1, x2].filter((r) => !r.error).length === 1, [msg(x1), msg(x2)]);

// ---------- Cancellation ----------
const cancel = await winner.c.rpc("cancel_my_appointment", { p_id: appt.id });
check("customer cancels own booking", !cancel.error, msg(cancel));
const row = await barberA.c.from("appointments").select("status, cancelled_at, cancelled_by").eq("id", appt.id).single();
check("cancelled booking is kept in history with who/when", row.data?.status === "cancelled" && !!row.data.cancelled_at && row.data.cancelled_by === winner.id);
const uncancel = await barberA.c.from("appointments").update({ status: "confirmed" }).eq("id", appt.id);
check("a cancelled booking cannot be revived", msg(uncancel).includes("ALREADY_CANCELLED"), msg(uncancel));
const rebook = await book(cust3, combo.id, plus(T, x1.error ? 240 : 480));
check("cancelled time can be booked again", !rebook.error, msg(rebook));
const barberCancel = await barberA.c.from("appointments").update({ status: "cancelled" }).eq("id", rebook.data!.id).select();
check("barber can cancel a booking in own shop", barberCancel.data?.[0]?.status === "cancelled", msg(barberCancel));

// ---------- Debts & payments ----------
const linked = await barberA.c.from("debts").insert({ barber_id: shopA!.id, customer_id: winner.id, customer_name: "زبون", amount: 20000 }).select().single();
check("barber records a debt on a customer account", !!linked.data && linked.data.customer_id === winner.id && linked.data.link_code === null, msg(linked));
const stranger = await barberA.c.from("debts").insert({ barber_id: shopA!.id, customer_id: barberB.id, customer_name: "غريب", amount: 1000 });
check("debt on an account with no link to the shop is rejected", msg(stranger).includes("CUSTOMER_NOT_IN_SHOP"), msg(stranger));
const winnerDebts = await winner.c.from("debts").select("id, amount");
check("customer sees own debt", winnerDebts.data?.length === 1 && winnerDebts.data[0]!.amount === 20000, msg(winnerDebts));
check("other customer sees none of it", ((await loser.c.from("debts").select("*")).data ?? []).length === 0);
check("barber B cannot see A's debts", ((await barberB.c.from("debts").select("*")).data ?? []).length === 0);

const p1 = await barberA.c.from("payments").insert({ debt_id: linked.data!.id, barber_id: shopA!.id, amount: 12000 });
check("partial payment saved", !p1.error, msg(p1));
const [q1, q2] = await Promise.all([
  barberA.c.from("payments").insert({ debt_id: linked.data!.id, barber_id: shopA!.id, amount: 6000 }),
  barberA.c.from("payments").insert({ debt_id: linked.data!.id, barber_id: shopA!.id, amount: 6000 }),
]);
check("two simultaneous payments that together exceed the balance: one rejected", [q1, q2].filter((r) => !r.error).length === 1, [msg(q1), msg(q2)]);
check("overpayment rejected", msg(await barberA.c.from("payments").insert({ debt_id: linked.data!.id, barber_id: shopA!.id, amount: 2001 })).includes("OVERPAYMENT"));
const full = await barberA.c.from("payments").insert({ debt_id: linked.data!.id, barber_id: shopA!.id, amount: 2000 });
check("final payment settles the debt exactly", !full.error, msg(full));
const custView = await winner.c.from("debts").select("amount, payments(amount)").eq("id", linked.data!.id).single();
const paidSum = (custView.data?.payments ?? []).reduce((s, p) => s + p.amount, 0);
check("customer sees payments; remaining = amount − payments = 0", paidSum === 20000 && custView.data!.amount - paidSum === 0, custView.data);

check("customer cannot add a payment", !!(await winner.c.from("payments").insert({ debt_id: linked.data!.id, barber_id: shopA!.id, amount: 1 })).error);
check("customer cannot create a debt", !!(await winner.c.from("debts").insert({ barber_id: shopA!.id, customer_name: "حيلة", amount: 5 })).error);
check("customer cannot edit a debt", ((await winner.c.from("debts").update({ note: "x" }).eq("id", linked.data!.id).select()).data ?? []).length === 0);
await barberA.c.from("debts").delete().eq("id", linked.data!.id);
check("debts cannot be deleted (history kept)", ((await barberA.c.from("debts").select("id").eq("id", linked.data!.id)).data ?? []).length === 1);
check("barber B cannot add payment to A's debt", !!(await barberB.c.from("payments").insert({ debt_id: linked.data!.id, barber_id: shopB!.id, amount: 1 })).error);

// Old debt recorded before the customer had an account → one-time code.
const walkIn = await barberA.c.from("debts").insert({ barber_id: shopA!.id, customer_name: "زبون قديم", amount: 7000 }).select().single();
const code = walkIn.data?.link_code ?? "";
check("debt without account gets a one-time link code", /^D-[A-Z2-9]{8}$/.test(code), code);
check("wrong code is rejected", msg(await cust3.c.rpc("claim_debt", { p_code: "D-AAAAAAAA" })).includes("INVALID_LINK_CODE"));
check("a barber account cannot claim debts", msg(await barberB.c.rpc("claim_debt", { p_code: code })).includes("NOT_A_CUSTOMER"));
const claim = await cust3.c.rpc("claim_debt", { p_code: code.toLowerCase() });
check("customer links the old debt with the code", !claim.error, msg(claim));
check("debt now appears for that customer", ((await cust3.c.from("debts").select("id").eq("id", walkIn.data!.id)).data ?? []).length === 1);
check("the code cannot be used twice", msg(await loser.c.rpc("claim_debt", { p_code: code })).includes("INVALID_LINK_CODE"));

// ---------- Persistence across sign-out / sign-in ----------
await winner.c.auth.signOut();
