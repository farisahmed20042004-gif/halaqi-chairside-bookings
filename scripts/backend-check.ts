import { createClient } from "@supabase/supabase-js";

const url = process.env.VITE_SUPABASE_URL!;
const key = process.env.VITE_SUPABASE_PUBLISHABLE_KEY!;
const stamp = Date.now();
let failures = 0;
const check = (name: string, ok: boolean, extra?: unknown) => {
  if (!ok) failures++;
  console.log(`${ok ? "PASS" : "FAIL"}  ${name}${extra !== undefined ? "  " + JSON.stringify(extra) : ""}`);
};

async function user(tag: string, fullName: string) {
  const c = createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
  const { data, error } = await c.auth.signUp({
    email: `halaqi.test.${tag}.${stamp}@example.com`,
    password: `Test-${stamp}-Xy9!q`,
    options: { data: { full_name: fullName, phone: "07700000000" } },
  });
  if (error || !data.session) throw new Error(`signup ${tag}: ${error?.message ?? "no session"}`);
  return { c, id: data.user!.id };
}

const barberA = await user("barbera", "حلاق أ");
const barberB = await user("barberb", "حلاق ب");
const cust1 = await user("cust1", "زبون ١");
const cust2 = await user("cust2", "زبون ٢");
check("sign-up gives an immediate session (no email confirmation)", true);

const prof = await cust1.c.from("profiles").select("full_name").single();
check("profile created on sign-up", prof.data?.full_name === "زبون ١", prof.error?.message);

const { data: shopA, error: eA } = await barberA.c
  .from("barbers")
  .insert({ owner_id: barberA.id, shop_name: "صالون أ", barber_name: "حلاق أ", code: "HACK-1" })
  .select()
  .single();
check("barber A creates shop", !!shopA, eA?.message);
check("code generated by server (client value ignored)", /^HLQ-[A-Z2-9]{6}$/.test(shopA?.code ?? ""), shopA?.code);
const { data: shopB } = await barberB.c
  .from("barbers")
  .insert({ owner_id: barberB.id, shop_name: "صالون ب", barber_name: "حلاق ب" })
  .select()
  .single();
check("codes are unique", !!shopB && shopB.code !== shopA!.code);

const upd = await barberA.c.from("barbers").update({ code: "HLQ-AAAAAA" }).eq("id", shopA!.id).select().single();
check("barber cannot change own code", upd.data?.code === shopA!.code);

const seeOther = await barberB.c.from("barbers").select("*").eq("id", shopA!.id);
check("barber B cannot read barber A shop row", (seeOther.data ?? []).length === 0);

const found = await cust1.c.rpc("find_barber_by_code", { p_code: " " + shopA!.code.toLowerCase() + " " });
check("customer finds barber by code (case/space tolerant)", found.data?.[0]?.id === shopA!.id, found.error?.message);
check("lookup does not expose owner id", !("owner_id" in (found.data?.[0] ?? {})));
const wrong = await cust1.c.rpc("find_barber_by_code", { p_code: "HLQ-ZZZZZZ" });
check("wrong code finds nothing", (wrong.data ?? []).length === 0);

const tomorrow = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Baghdad" }).format(new Date(Date.now() + 86400000));
const slots = await cust1.c.rpc("get_available_slots", { p_barber_id: shopA!.id, p_day: tomorrow });
check("slots listed for tomorrow (10:00–21:00 every 30 min = 22)", slots.data?.length === 22, slots.error?.message ?? slots.data?.length);
const target = slots.data![4]!.starts_at;

// Two customers try to book the exact same slot at the same moment.
const [r1, r2] = await Promise.all([
  cust1.c.rpc("book_appointment", { p_barber_id: shopA!.id, p_starts_at: target, p_service: "قص شعر", p_customer_name: "زبون ١" }),
  cust2.c.rpc("book_appointment", { p_barber_id: shopA!.id, p_starts_at: target, p_service: "قص شعر", p_customer_name: "زبون ٢" }),
]);
const wins = [r1, r2].filter((r) => !r.error);
const losers = [r1, r2].filter((r) => r.error);
check("simultaneous booking: exactly one succeeds", wins.length === 1, [r1.error?.message, r2.error?.message]);
check("the other gets SLOT_TAKEN", losers[0]?.error?.message?.includes("SLOT_TAKEN") ?? false, losers[0]?.error?.message);
check("booking is confirmed immediately", wins[0]?.data?.status === "confirmed");

const winner = r1.error ? cust2 : cust1;
const loser = r1.error ? cust1 : cust2;

const again = await cust1.c.rpc("get_available_slots", { p_barber_id: shopA!.id, p_day: tomorrow });
check("slot now shows as booked", again.data?.find((s) => s.starts_at === target)?.available === false);

const offGrid = new Date(new Date(target).getTime() + 7 * 60000).toISOString();
const bad = await cust1.c.rpc("book_appointment", { p_barber_id: shopA!.id, p_starts_at: offGrid, p_service: "قص", p_customer_name: "زبون ١" });
check("off-schedule time rejected", bad.error?.message.includes("OUTSIDE_HOURS") ?? false, bad.error?.message);
const past = await cust1.c.rpc("book_appointment", { p_barber_id: shopA!.id, p_starts_at: new Date(Date.now() - 3600e3).toISOString(), p_service: "قص", p_customer_name: "زبون ١" });
check("past time rejected", past.error?.message.includes("SLOT_IN_PAST") ?? false, past.error?.message);

const loserSees = await loser.c.from("appointments").select("*");
check("other customer cannot see the booking", (loserSees.data ?? []).length === 0);
const winnerSees = await winner.c.rpc("get_my_appointments");
check("booking customer sees own booking", winnerSees.data?.length === 1, winnerSees.error?.message);
const aSees = await barberA.c.from("appointments").select("*").eq("barber_id", shopA!.id);
check("barber A sees the booking", aSees.data?.length === 1);
const bSees = await barberB.c.from("appointments").select("*");
check("barber B cannot see barber A's bookings", (bSees.data ?? []).length === 0);

const custUpd = await winner.c.from("appointments").update({ status: "completed" }).eq("id", wins[0]!.data!.id).select();
check("customer cannot change status directly", (custUpd.data ?? []).length === 0);
const bUpd = await barberB.c.from("appointments").update({ status: "cancelled" }).eq("id", wins[0]!.data!.id).select();
check("barber B cannot change barber A's booking", (bUpd.data ?? []).length === 0);

const directInsert = await cust1.c.from("appointments").insert({ barber_id: shopA!.id, customer_name: "x y", service: "قص", starts_at: target } as never);
check("direct insert (bypassing rules) is blocked", !!directInsert.error);

const cancel = await winner.c.rpc("cancel_my_appointment", { p_id: wins[0]!.data!.id });
check("customer can cancel own booking", !cancel.error, cancel.error?.message);
const freed = await cust1.c.rpc("get_available_slots", { p_barber_id: shopA!.id, p_day: tomorrow });
check("cancelled slot becomes free again", freed.data?.find((s) => s.starts_at === target)?.available === true);

// Debts & payments
const { data: debt, error: dErr } = await barberA.c
  .from("debts")
  .insert({ barber_id: shopA!.id, customer_name: "زبون مدين", amount: 20000 })
  .select()
  .single();
check("barber records a debt", !!debt, dErr?.message);
const p1 = await barberA.c.from("payments").insert({ debt_id: debt!.id, barber_id: shopA!.id, amount: 15000 });
check("partial payment saved", !p1.error, p1.error?.message);
const p2 = await barberA.c.from("payments").insert({ debt_id: debt!.id, barber_id: shopA!.id, amount: 10000 });
check("overpayment rejected", p2.error?.message.includes("OVERPAYMENT") ?? false, p2.error?.message);
const bDebt = await barberB.c.from("debts").select("*");
check("barber B cannot see A's debts", (bDebt.data ?? []).length === 0);
const bPay = await barberB.c.from("payments").insert({ debt_id: debt!.id, barber_id: shopB!.id, amount: 1000 });
check("barber B cannot add payment to A's debt", !!bPay.error, bPay.error?.message);
const cDebt = await cust1.c.from("debts").select("*");
check("customer cannot see debts", (cDebt.data ?? []).length === 0);
const bDebtIns = await barberB.c.from("debts").insert({ barber_id: shopA!.id, customer_name: "حيلة", amount: 5 });
check("barber B cannot add debt to A's shop", !!bDebtIns.error);

console.log(failures === 0 ? "\nALL PASSED" : `\n${failures} FAILED`);
console.log("TEST_USER_IDS", [barberA.id, barberB.id, cust1.id, cust2.id].join(","));
